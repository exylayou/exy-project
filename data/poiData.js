/**
 * Get POI data based on filter selection
 * @param {string} filter - The active filter name
 * @returns {Array} - Array of POI objects
 */
export const getPoiByFilter = (filter) => {
  switch (filter) {
    case 'BEACHES':
      return beachPois;
    case 'CULTURAL':
      return culturalPois;
    case 'OUTDOOR & ADVENTURE':
      return outdoorPois;
    case 'RESTAURANTS':
      return restaurantPois;
    case 'THINGS TO DO':
      return thingsToDoePois;
    case 'FOR YOU':
    default:
      return defaultPois;
  }
};
